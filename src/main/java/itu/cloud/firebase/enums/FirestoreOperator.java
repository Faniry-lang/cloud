package itu.cloud.firebase.enums;

public enum FirestoreOperator {

    EQUALS,                     // ==
    NOT_EQUALS,                 // !=
    GREATER_THAN,               // >
    GREATER_THAN_OR_EQUAL,      // >=
    LESS_THAN,                  // <
    LESS_THAN_OR_EQUAL,         // <=
    IN,                         // in
    NOT_IN,                     // not-in
    ARRAY_CONTAINS              // array-contains
}
